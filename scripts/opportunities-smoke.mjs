#!/usr/bin/env node
// Focused browser-DOM smoke test for the new discovery surface; no network writes.
import fs from 'node:fs';
import { JSDOM, VirtualConsole } from 'jsdom';
import assert from 'node:assert/strict';
const html = fs.readFileSync('dist/index.html', 'utf8');
const js = html.match(/src="\.?\/?assets\/(index-[^"]+\.js)"/)?.[1];
assert.ok(js, 'production bundle missing');
const errors = [];
const vc = new VirtualConsole();
vc.on('jsdomError', e => errors.push(e.message));
vc.on('error', (...args) => errors.push(args.join(' ')));
const dom = new JSDOM(html, { url: 'http://localhost:3000/#/opportunities?q=%D9%BE%D8%B1%D9%88%DA%98%D9%87%20%D8%A2%D8%B2%D9%85%D8%A7%DB%8C%D8%B4%20%D9%85%D8%B3%D8%AA%D9%82%D9%84', runScripts: 'outside-only', pretendToBeVisual: true, virtualConsole: vc });
const w = dom.window;
w.matchMedia = q => ({ matches:false, media:q, addListener(){}, removeListener(){}, addEventListener(){}, removeEventListener(){} });
w.fetch = async () => new Response('{}', { status: 401, headers: { 'content-type': 'application/json' } });
w.ResizeObserver = class { observe(){} unobserve(){} disconnect(){} };
w.IntersectionObserver = class { observe(){} unobserve(){} disconnect(){} };
w.scrollTo = () => {};
w.HTMLElement.prototype.scrollIntoView = () => {};
w.localStorage.setItem('konklancer_language', 'en');
w.localStorage.setItem('freelanceflow_jobs', JSON.stringify([{ id:'manual-smoke', title:'پروژه آزمایش مستقل', description:'شرح پروژه برای تست', platform:'پونیشا', platformKey:'ponisha', budget:1200000, budgetFormatted:'۱٬۲۰۰٬۰۰۰ تومان', category:'وب', categoryKey:'development', tags:['react'], status:'new', postedTime:'همین حالا', proposalsCount:0, isManual:true, pinned:true }]));
w.eval(fs.readFileSync(`dist/assets/${js}`, 'utf8').replace(/export\{[^}]*\};?\s*$/, '').replaceAll('import.meta.resolve', 'undefined').replaceAll('import.meta.url', JSON.stringify(`http://localhost:3000/assets/${js}`)));
const wait = async (fn) => { for (let i=0;i<100;i++) { if (fn()) return; await new Promise(r=>setTimeout(r,100)); } throw new Error('DOM condition timed out: ' + w.document.body.textContent.slice(0,500) + ' errors: ' + errors.join('; ')); };
await wait(() => w.document.querySelector('.table-row'));
assert.ok(w.document.querySelector('.field-search input'), 'search control');
const row = [...w.document.querySelectorAll('.table-row')].find(el => el.textContent.includes('پروژه آزمایش مستقل'));
assert.ok(row, 'seeded job is visible');
row.dispatchEvent(new w.MouseEvent('click', { bubbles:true }));
await wait(() => w.document.querySelector('.page-heading h1')?.textContent.includes('پروژه آزمایش مستقل'));
assert.match(w.document.querySelector('.page-heading h1').textContent, /پروژه آزمایش مستقل/);
assert.ok(w.location.hash.includes('/opportunities/manual-smoke'), 'detail is deep linked');
const stageSelect = w.document.querySelector('.detail-side select');
stageSelect.value = 'bidded';
stageSelect.dispatchEvent(new w.Event('change', { bubbles:true }));
await wait(() => JSON.parse(w.localStorage.getItem('freelanceflow_jobs')).some(j => j.id === 'manual-smoke' && j.status === 'bidded'));
w.location.hash = '#/pipeline?stage=bidded';
await wait(() => [...w.document.querySelectorAll('.pipeline-row')].some(el => el.textContent.includes('پروژه آزمایش مستقل')));
const toggle = w.document.querySelector('.language-toggle');
toggle.dispatchEvent(new w.MouseEvent('click', { bubbles:true }));
await wait(() => w.document.documentElement.dir === 'rtl' && w.document.body.textContent.includes('مراحل کار'));
assert.equal(w.localStorage.getItem('konklancer_language'), 'fa');
toggle.dispatchEvent(new w.MouseEvent('click', { bubbles:true }));
await wait(() => w.document.documentElement.dir === 'ltr' && w.document.body.textContent.includes('Pipeline'));
const command = w.document.querySelector('.command-button');
command.focus();
command.dispatchEvent(new w.MouseEvent('click', { bubbles:true }));
await wait(() => w.document.querySelector('[role="dialog"][aria-label="Command menu"]'));
const dialog = w.document.querySelector('[role="dialog"][aria-label="Command menu"]');
assert.ok(dialog.contains(w.document.activeElement), 'dialog receives focus');
w.document.dispatchEvent(new w.KeyboardEvent('keydown', { key:'Escape', bubbles:true }));
await wait(() => !w.document.querySelector('[role="dialog"]'));
assert.ok(w.document.activeElement === command, 'dialog restores focus');
w.location.hash = '#/settings';
await wait(() => [...w.document.querySelectorAll('button')].some(el => el.textContent === 'Check cloud feed'));
const checkCloud = [...w.document.querySelectorAll('button')].find(el => el.textContent === 'Check cloud feed');
checkCloud.dispatchEvent(new w.MouseEvent('click', { bubbles:true }));
await wait(() => w.document.querySelector('#operations-title')?.parentElement?.textContent.includes('HTTP 401'));
assert.ok(w.document.querySelector('[role="alert"]'), 'API authentication failure is visible');
w.location.hash = '#/analytics';
await wait(() => w.location.hash === '#/insights');
assert.equal(errors.length, 0, errors.join('\n'));
console.log('New frontend: discovery, detail, persistence, pipeline, modal focus, API error and legacy route redirect passed');
dom.window.close();
